// Snap the picked card renders into game files and generate src/data/cardart.ts from the manifests.
// usage: node tools/art/build-cards.mjs <render dir> [--names-only | --partial]
//   --partial skips cards whose render is not there yet (for checking work in progress); they show NO ART.
//   Picks: seed index 0 of each job unless tools/art/card-picks.txt says otherwise ("<id> <seed>" or "<id> none").
//   Output: public/art/cards/<file>.png (64 x 48) and public/art/cards/x2/<file>.png (128 x 96), where <file> is the
//   card id with '@asc' written as '.asc'.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { JOBS, FACTIONS } from './jobs-cards.mjs';
import { snapScene } from './snap.mjs';

const [dir, flag] = process.argv.slice(2);
const missing = new Set();
export const fileOf = (id) => id.replace('@asc', '.asc');

const picks = new Map();
if (existsSync('tools/art/card-picks.txt')) {
  for (const line of readFileSync('tools/art/card-picks.txt', 'utf8').split(/\r?\n/)) {
    const t = line.trim();
    if (!t || t.startsWith('#')) continue;
    const [id, seed] = t.split(/\s+/);
    picks.set(id, seed);
  }
}

if (flag !== '--names-only') {
  mkdirSync('public/art/cards/x2', { recursive: true });
  let n = 0;
  for (const j of JOBS) {
    const p = picks.get(j.id);
    if (p === 'none') continue;
    const seed = p ? Number(p) : j.seeds[0];
    const src = `${dir}/${j.id}-s${seed}.png`;
    if (!existsSync(src)) {
      if (flag === '--partial') { missing.add(j.id.replace('@asc', '')); continue; }
      throw new Error(`build-cards: missing render ${src}`);
    }
    await snapScene(src, `public/art/cards/${fileOf(j.id)}.png`, 64, 48, 48);
    await snapScene(src, `public/art/cards/x2/${fileOf(j.id)}.png`, 128, 96, 64);
    n++;
  }
  console.log('snapped', n);
}

const rows = [];
for (const f of FACTIONS) {
  for (const c of f.CARDS) {
    const art = picks.get(c.id) !== 'none' && !missing.has(c.id);
    const asc = c.ascendedName ? `, ascendedName: ${JSON.stringify(c.ascendedName)}` : '';
    rows.push(`  ${JSON.stringify(c.id)}: { faction: ${JSON.stringify(f.FACTION)}, name: ${JSON.stringify(c.name)}${asc}, art: ${art} },`);
  }
}
writeFileSync('src/data/cardart.ts', `// Generated by tools/art/build-cards.mjs from tools/art/cards/*.mjs. Do not edit by hand.
// Proposed Magitek Wars names (PLAN D12, pending Q5) and whether a card has art in public/art/cards/.
export interface CardArt { faction: string; name: string; ascendedName?: string; art: boolean }

export const CARD_ART: Record<string, CardArt> = {
${rows.join('\n')}
};
`);
console.log('cardart.ts', rows.length);
